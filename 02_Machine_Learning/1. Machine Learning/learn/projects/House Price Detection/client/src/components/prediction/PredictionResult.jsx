import React from 'react';
import { formatINR } from '../../utils/formatCurrency';
import { CheckCircle2, Cpu, AlertTriangle } from 'lucide-react';

export const PredictionResult = ({ result, submittedProperty, className = '' }) => {
  if (!result || !result.prediction) return null;

  const { price_inr, price_lakh, price_crore } = result.prediction;
  const builtUpArea = submittedProperty?.built_up_area_sqft || 0;
  const pricePerSqft = builtUpArea > 0 ? Math.round(price_inr / builtUpArea) : null;

  return (
    <div
      className={`rounded-3xl bg-gradient-to-br from-emerald-900 via-slate-900 to-slate-950 text-white p-6 sm:p-8 shadow-xl border border-emerald-500/20 relative overflow-hidden animate-in fade-in duration-300 ${className}`}
    >
      {/* Decorative Glow */}
      <div className="absolute -top-24 -right-24 w-64 h-64 bg-emerald-500/10 rounded-full blur-3xl pointer-events-none" />

      {/* Header Badge */}
      <div className="flex items-center justify-between gap-2 mb-6">
        <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-emerald-500/15 border border-emerald-500/30 text-emerald-400 text-xs font-semibold">
          <CheckCircle2 className="w-3.5 h-3.5" />
          <span>Model Valuation Computed</span>
        </div>
        <div className="flex items-center gap-1.5 text-xs text-slate-400">
          <Cpu className="w-3.5 h-3.5 text-emerald-400" />
          <span>{result.model?.name || 'Indian House Price Predictor'} v{result.model?.version || '1.0.0'}</span>
        </div>
      </div>

      {/* Main Valuation Figure */}
      <div className="mb-6">
        <span className="text-xs uppercase tracking-wider text-slate-400 font-semibold block mb-1">
          Estimated Property Value
        </span>
        <div className="text-3xl sm:text-5xl font-extrabold tracking-tight text-white flex items-baseline gap-2">
          <span>{formatINR(price_inr)}</span>
        </div>

        {/* Lakhs & Crores Breakdown */}
        <div className="flex items-center gap-4 mt-3 text-sm text-slate-300 font-medium">
          <div className="px-3 py-1 rounded-xl bg-white/5 border border-white/10">
            <span className="text-slate-400 text-xs mr-1.5">Lakhs:</span>
            <span className="text-emerald-400 font-bold">₹ {price_lakh} L</span>
          </div>
          <div className="px-3 py-1 rounded-xl bg-white/5 border border-white/10">
            <span className="text-slate-400 text-xs mr-1.5">Crores:</span>
            <span className="text-emerald-400 font-bold">₹ {price_crore} Cr</span>
          </div>
        </div>
      </div>

      {/* Metric Breakdown Cards */}
      <div className="grid grid-cols-2 sm:grid-cols-3 gap-3 pt-6 border-t border-white/10">
        <div className="p-3.5 rounded-2xl bg-white/5 border border-white/5">
          <div className="text-[11px] text-slate-400 font-medium mb-1">Price / Sq Ft</div>
          <div className="text-base font-bold text-white">
            {pricePerSqft ? `₹ ${pricePerSqft.toLocaleString('en-IN')}` : 'N/A'}
          </div>
          <div className="text-[10px] text-emerald-400 mt-0.5">Calculated on built-up</div>
        </div>

        <div className="p-3.5 rounded-2xl bg-white/5 border border-white/5">
          <div className="text-[11px] text-slate-400 font-medium mb-1">Configuration</div>
          <div className="text-base font-bold text-white">
            {submittedProperty?.bedrooms || 0} BHK
          </div>
          <div className="text-[10px] text-slate-400 mt-0.5">
            {submittedProperty?.bathrooms || 0} Bath &bull; {submittedProperty?.property_type || 'Residential'}
          </div>
        </div>

        <div className="p-3.5 rounded-2xl bg-white/5 border border-white/5 col-span-2 sm:col-span-1">
          <div className="text-[11px] text-slate-400 font-medium mb-1">Micro-market</div>
          <div className="text-sm font-bold text-white truncate">
            {submittedProperty?.village_locality || submittedProperty?.district || 'India'}
          </div>
          <div className="text-[10px] text-slate-400 mt-0.5 truncate">
            {submittedProperty?.state}
          </div>
        </div>
      </div>

      {/* Synthetic Model Disclaimer Note */}
      <div className="mt-6 flex items-start gap-2 text-[11px] text-slate-400 leading-relaxed bg-white/5 p-3 rounded-xl border border-white/5">
        <AlertTriangle className="w-4 h-4 text-amber-400 shrink-0 mt-0.5" />
        <span>
          <strong>Disclaimer: </strong> This estimate is generated by a Machine Learning regression pipeline. It represents a synthetic data prediction for demonstration and analytical exploration, not a licensed real estate appraisal.
        </span>
      </div>
    </div>
  );
};

export default PredictionResult;
