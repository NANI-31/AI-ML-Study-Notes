# --- MODULE-SCOPE HELPER CLASSES FOR WORKBENCH ---
class MockMessageState:
    """Represents an atomic message record in module scope."""
    def __init__(self, role: str, content: Union[str, List[Dict[str, Any]]], 
                 tool_calls: Optional[List[Dict[str, Any]]] = None,
                 tool_call_id: Optional[str] = None,
                 token_count: int = 0):
        self.role = role
        self.content = content
        self.tool_calls = tool_calls or []
        self.tool_call_id = tool_call_id
        self.token_count = token_count

class MockMessageHistoryEngine:
    """Simulates multi-turn conversation buffering, tool calling cycles, and message trimming."""
    def __init__(self, max_token_limit: int = 1000):
        self.max_token_limit = max_token_limit
        self.messages: List[MockMessageState] = []

    def add_message(self, role: str, content: Union[str, List[Dict[str, Any]]], 
                    tool_calls: Optional[List[Dict[str, Any]]] = None,
                    tool_call_id: Optional[str] = None) -> MockMessageState:
        # Approximate token count (roughly 4 characters per token)
        text_repr = str(content) + str(tool_calls or "")
        est_tokens = max(5, len(text_repr) // 4)
        msg = MockMessageState(role, content, tool_calls, tool_call_id, est_tokens)
        self.messages.append(msg)
        return msg

    def get_total_tokens(self) -> int:
        return sum(m.token_count for m in self.messages)

    def trim_history(self, strategy: str = "last_k", max_messages: int = 6) -> List[MockMessageState]:
        """Simulates LangChain trim_messages logic."""
        if strategy == "last_k":
            # Retain SystemMessage at index 0 if present, then last K messages
            if self.messages and self.messages[0].role == "SystemMessage":
                sys_msg = [self.messages[0]]
                rest = [m for m in self.messages[1:]]
                trimmed = sys_msg + rest[-max_messages:]
            else:
                trimmed = self.messages[-max_messages:]
            return trimmed
        elif strategy == "token_budget":
            budget = self.max_token_limit
            trimmed_rev = []
            sys_msg = self.messages[0] if (self.messages and self.messages[0].role == "SystemMessage") else None
            
            if sys_msg:
                budget -= sys_msg.token_count

            for m in reversed(self.messages[1:] if sys_msg else self.messages):
                if budget - m.token_count >= 0:
                    trimmed_rev.append(m)
                    budget -= m.token_count
                else:
                    break
            result = list(reversed(trimmed_rev))
            if sys_msg:
                result.insert(0, sys_msg)
            return result
        return self.messages

