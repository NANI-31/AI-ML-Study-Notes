qa_tab, traps_tab, flashcards_tab = st.tabs(["High-Frequency Questions", "Schema Traps", "Flashcards"])

with qa_tab:
    st.markdown("""
    **Q1: Why do Vector Database collections mandate a fixed vector dimensionality (e.g. d = 768)?**
    * **Answer**:
      * In linear algebra, inner products, cosine similarities, and Euclidean distances are mathematically defined **only between vectors of identical dimensionality**:
        $u \\cdot v = \\sum_{i=1}^d u_i v_i$.
      * You cannot compute the dot product between a 384-d vector (MiniLM) and a 1536-d vector (OpenAI).
      * Furthermore, the underlying ANN index (HNSW graph) allocates fixed-size contiguous memory buffers per node.
      * Mixing different embedding models in the same collection produces invalid geometry and crashes index traversals.

    **Q2: What is an 'Idempotent Upsert' and why is it critical in production data pipelines?**
    * **Answer**:
      * **Idempotence**: Performing an operation multiple times produces the exact same state as performing it once.
      * If an ingestion worker processes a document with `id="legal_contract_v2"`, an idempotent `upsert`:
        * Inserts the record if `"legal_contract_v2"` does not exist.
        * Atomically updates and overwrites the vector and metadata if `"legal_contract_v2"` already exists.
      * Without idempotent upserts, retrying a failed pipeline worker would create duplicate vector records for the same document, polluting search results.

    **Q3: How do secondary metadata indexes accelerate single-stage filtered search?**
    * **Answer**:
      * Advanced vector databases (e.g. Qdrant, ChromaDB, Weaviate) do not simply scan JSON dictionaries.
      * They build secondary **Roaring Bitmaps** or inverted indexes over metadata fields (e.g. `department`, `tenant_id`).
      * When a query arrives with `where={'tenant_id': 42}`, the engine creates a bitmask of valid vector IDs in microseconds.
      * During HNSW graph exploration, the engine consults the bitmask to immediately prune invalid nodes before computing dot products.
    """)

with traps_tab:
    st.markdown("""
    * **Trap 1: Mixing Embeddings from Different Models in the Same Collection**:
      * *Issue*: Ingesting some documents with `text-embedding-ada-002` (1536-d) and new documents with `text-embedding-3-small` (1536-d).
      * *Consequence*: Even though both have 1,536 dimensions, the coordinate spaces are completely different manifolds! Distance scores between them are meaningless random numbers.
      * *Fix*: Re-index the entire collection whenever switching model checkpoints.

    * **Trap 2: Storing Volatile User Session State in Document Metadata**:
      * *Issue*: Updating `metadata['last_viewed_at']` on vector records every second.
      * *Consequence*: Causes continuous write-ahead log (WAL) churn and forces repeated index segment compaction.
      * *Fix*: Store dynamic user session data in Redis or PostgreSQL; keep vector DB metadata strictly focused on immutable document attributes.

    * **Trap 3: Mismatching Collection Metric and Model Normalization**:
      * *Issue*: Configuring a collection with `metric="euclidean"` for a model trained with cosine loss.
      * *Consequence*: If vectors are not unit-normalized, long texts will be penalized by high Euclidean distances.
      * *Fix*: Use `metric="cosine"` or pre-normalize vectors and use `metric="dot"`.
    """)

