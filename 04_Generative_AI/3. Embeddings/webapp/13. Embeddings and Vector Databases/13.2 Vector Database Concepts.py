st.code(r'''
import numpy as np
from typing import List, Dict, Any, Optional

class VectorCollection:
    """
    Production-grade Vector Database Collection model.
    Enforces fixed dimensions, collection-level distance metrics,
    idempotent upserts, and payload metadata filtering.
    """
    def __init__(self, name: str, dimension: int, metric: str = "cosine"):
        self.name = name
        self.dimension = dimension
        self.metric = metric.lower() # "cosine", "dot", "euclidean"
        self.records: Dict[str, Dict[str, Any]] = {}

    def upsert(self, doc_id: str, vector: np.ndarray, text: str, metadata: Dict[str, Any]):
        """Idempotently inserts or updates a document record."""
        vec = np.asarray(vector, dtype=np.float32).flatten()
        if len(vec) != self.dimension:
            raise ValueError(f"Vector dimension {len(vec)} does not match collection dimension {self.dimension}")

        # Unit normalize if cosine metric
        if self.metric == "cosine":
            norm = np.linalg.norm(vec)
            vec = vec / np.maximum(norm, 1e-12)

        self.records[doc_id] = {
            "id": doc_id,
            "vector": vec,
            "text": text,
            "metadata": metadata
        }

    def query(
        self, 
        query_vector: np.ndarray, 
        where_filter: Dict[str, Any] = None, 
        top_k: int = 3
    ) -> List[Dict[str, Any]]:
        """Queries collection with optional metadata equality filter."""
        q_vec = np.asarray(query_vector, dtype=np.float32).flatten()
        if self.metric == "cosine":
            q_vec = q_vec / np.maximum(np.linalg.norm(q_vec), 1e-12)

        scored = []
        for doc_id, rec in self.records.items():
            # Check metadata filters
            if where_filter:
                match = all(rec["metadata"].get(k) == v for k, v in where_filter.items())
                if not match:
                    continue

            # Compute similarity score
            if self.metric in ["cosine", "dot"]:
                score = float(np.dot(q_vec, rec["vector"]))
            else: # euclidean
                dist = float(np.linalg.norm(q_vec - rec["vector"]))
                score = 1.0 / (1.0 + dist) # Invert distance to similarity

            scored.append({
                "id": doc_id,
                "score": score,
                "text": rec["text"],
                "metadata": rec["metadata"]
            })

        scored.sort(key=lambda x: x["score"], reverse=True)
        return scored[:top_k]
''', language="python")

# Actual Python implementation for the interactive workbench
class InteractiveCollectionStudio:
    def __init__(self):
        self.collections: Dict[str, Any] = {}
        # Pre-seed sample collection
        self.create_collection("tech_support_tickets", dimension=3, metric="cosine")
        self.upsert_doc("tech_support_tickets", "TICK_01", np.array([0.95, 0.05, 0.02]), "Cannot reset password", {"priority": "high", "dept": "auth"})
        self.upsert_doc("tech_support_tickets", "TICK_02", np.array([0.05, 0.96, 0.02]), "Double billing on credit card", {"priority": "medium", "dept": "finance"})
        self.upsert_doc("tech_support_tickets", "TICK_03", np.array([0.02, 0.05, 0.98]), "REST API 429 rate limit exceeded", {"priority": "high", "dept": "api"})

    def create_collection(self, name: str, dimension: int, metric: str):
        self.collections[name] = {
            "name": name,
            "dimension": dimension,
            "metric": metric,
            "docs": {}
        }

    def upsert_doc(self, coll_name: str, doc_id: str, vec: np.ndarray, text: str, meta: Dict[str, Any]):
        coll = self.collections[coll_name]
        norm = np.linalg.norm(vec)
        norm_v = vec / np.maximum(norm, 1e-12)
        coll["docs"][doc_id] = {
            "id": doc_id,
            "vector": norm_v,
            "text": text,
            "metadata": meta
        }

    def search(self, coll_name: str, q_vec: np.ndarray, dept_filter: str = None) -> List[Dict[str, Any]]:
        coll = self.collections[coll_name]
        norm_q = q_vec / np.linalg.norm(q_vec)
        hits = []
        for doc_id, item in coll["docs"].items():
            if dept_filter and dept_filter != "All" and item["metadata"].get("dept") != dept_filter:
                continue
            score = float(np.dot(norm_q, item["vector"]))
            hits.append({
                "id": doc_id,
                "score": score,
                "text": item["text"],
                "dept": item["metadata"].get("dept"),
                "priority": item["metadata"].get("priority")
            })
        hits.sort(key=lambda x: x["score"], reverse=True)
        return hits

